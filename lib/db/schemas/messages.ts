import { sql } from "drizzle-orm";
import { check, index, pgTable, text, uniqueIndex, uuid } from "drizzle-orm/pg-core";

import { user } from "./auth";
import { createdAt, pk, tstz } from "./helpers";
import { room } from "./rooms";

/**
 * Room messages. PostgreSQL is the source of truth; Socket.IO only delivers
 * them (PROJECT.md section 8).
 */
export const message = pgTable(
  "message",
  {
    id: pk(),
    roomId: uuid("room_id")
      .notNull()
      .references(() => room.id, { onDelete: "cascade" }),
    /** SET NULL keeps the history when an account is deleted. */
    senderId: text("sender_id").references(() => user.id, { onDelete: "set null" }),
    content: text("content").notNull(),
    /**
     * Idempotency key generated by the client for each send. A retry after a
     * reconnect hits the unique index below instead of creating a duplicate
     * (PROJECT.md Phase 7).
     */
    clientId: uuid("client_id"),
    createdAt: createdAt(),
    /** Set when the sender edits the message. */
    editedAt: tstz("edited_at"),
    /** Soft delete: the row stays so pagination and replies stay stable. */
    deletedAt: tstz("deleted_at"),
  },
  (t) => [
    // History pagination: newest first, per room, keyset on (createdAt, id).
    index("message_room_created_idx").on(t.roomId, t.createdAt.desc(), t.id.desc()),
    // NULL client ids are allowed (and never collide); real ones are unique per sender.
    uniqueIndex("message_sender_client_unique").on(t.senderId, t.clientId),
    check("message_content_length", sql`char_length(${t.content}) between 1 and 4000`),
  ],
);
